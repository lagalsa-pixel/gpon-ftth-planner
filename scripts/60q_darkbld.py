hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
h, s, v = hsv[:, :, 0], hsv[:, :, 1], hsv[:, :, 2]
# тёмная крыша: тёмная (V<115), слабонасыщенная, НЕ зелёная (не трава)
dark = ((v < 115) & (s < 130) & ~((h > 35) & (h < 85) & (s > 60))).astype(np.uint8)

results = []
for (mx, my, tag) in CANDS:
    ix, iy = mos2img(mx, my)
    ix, iy = int(round(ix)), int(round(iy))
    if not (40 <= ix < W - 40 and 40 <= iy < H - 40):
        continue
    # окно: квадрат в правом-нижнем углу; здание к западу и чуть севернее
    # окно 220x90 px (42x17 м): x ix-220..ix, y iy-70..iy+20
    x0, y0 = ix - 220, iy - 70
    win = dark[y0:iy + 20, x0:ix]
    if win.size == 0:
        continue
    # связные блобы в окне
    n, lab, st, cent = cv2.connectedComponentsWithStats(win * 255, 8)
    best = None
    for i in range(1, n):
        x, y, w2, h2, a = st[i]
        if a < 700:            # >= 25 м2
            continue
        if w2 < 90:            # длина >= 17 м
            continue
        if h2 > 60:            # не слишком толстое
            continue
        fill = a / (w2 * h2)
        if fill < 0.4:
            continue
        if best is None or a > best[0]:
            best = (a, x, y, w2, h2, fill)
    if best:
        a, x, y, w2, h2, fill = best
        results.append(dict(mos=(mx, my), tag=tag, img=(ix, iy),
                            bld_px=(x0 + x, y0 + y, w2, h2),
                            bld_m=(round(w2 * MPP, 1), round(h2 * MPP, 1)),
                            area=a, fill=round(fill, 2)))
        print(f'({mx},{my}) {tag}: ТЁМНОЕ ЗДАНИЕ {w2*MPP:.0f}x{h2*MPP:.0f} м '
              f'({w2}x{h2}px) у ({x0+x},{y0+y}), заполнение {fill:.2f}')

print(f'\nкандидатов с тёмным зданием к западу: {len(results)}')
json.dump(results, open(f'{BASE}/work/altay3/t60_darkbld.json', 'w'),
          ensure_ascii=False, indent=1)
